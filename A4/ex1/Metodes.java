package ex1;
public class Metodes {
    public static int suma(int a, int b){
        return a + b;
    }

    public static int resta(int a, int b){
        return a - b;
    }

    public static int multiplicacio(int a, int b){
        return a * b;
    }

    public static int divisio(int a, int b){
        return a / b;
    }
}